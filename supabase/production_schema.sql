create table public.arqueos_caja (
  id uuid primary key default gen_random_uuid(),
  usuario_id uuid not null references public.perfiles(id),
  fecha date not null default current_date,
  hora_apertura timestamptz not null default now(),
  hora_cierre timestamptz,
  fondo_inicial numeric(10,2) not null check (fondo_inicial >= 0),
  ventas_efectivo numeric(10,2) not null default 0 check (ventas_efectivo >= 0),
  ventas_tarjeta numeric(10,2) not null default 0 check (ventas_tarjeta >= 0),
  ventas_credito numeric(10,2) not null default 0 check (ventas_credito >= 0),
  gastos_dia numeric(10,2) not null default 0 check (gastos_dia >= 0),
  retiros_caja numeric(10,2) not null default 0 check (retiros_caja >= 0),
  efectivo_esperado numeric(10,2) generated always as
    (fondo_inicial + ventas_efectivo - gastos_dia - retiros_caja) stored,
  efectivo_contado numeric(10,2),
  diferencia numeric(10,2) generated always as
    (coalesce(efectivo_contado, 0) - (fondo_inicial + ventas_efectivo - gastos_dia - retiros_caja)) stored,
  justificacion text,
  autorizado_por uuid references public.perfiles(id),
  estado public.estado_arqueo not null default 'ABIERTO',
  unique (usuario_id, fecha),
  constraint arqueo_cierre_consistente check (
    (estado = 'ABIERTO' and hora_cierre is null and efectivo_contado is null)
    or (estado in ('CERRADO', 'AUDITADO') and hora_cierre is not null and efectivo_contado is not null)
  )
);

