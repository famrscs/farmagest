create or replace function public.farmagest_unaccent(value text)
returns text
language sql
immutable
parallel safe
strict
set search_path = ''
as $$
  select public.unaccent('public.unaccent', value);
$$;

create type public.user_role as enum ('ADMIN', 'CAJERO');
