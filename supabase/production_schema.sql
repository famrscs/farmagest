create table public.perfiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nombre_completo text not null,
  rol public.user_role not null default 'CAJERO',
  activo boolean not null default true,
  fecha_creacion timestamptz not null default now()
);

create table public.laboratorios (
  id uuid primary key default gen_random_uuid(),
  nombre text not null,
  direccion text,
  telefono text,
  contacto text,
  activo boolean not null default true
);

create table public.productos (
  id uuid primary key default gen_random_uuid(),
  codigo_interno text unique not null,
  nombre_comercial text not null,
  principio_activo text,
  laboratorio_id uuid references public.laboratorios(id),
  presentacion text,
  unidad_medida public.unidad_medida not null,
  cantidad_por_envase integer not null default 1 check (cantidad_por_envase > 0),
  costo_unitario numeric(10,2) not null check (costo_unitario >= 0),
  precio_venta numeric(10,2) not null check (precio_venta >= 0),
  stock_minimo integer not null default 5 check (stock_minimo >= 0),
  iva boolean not null default false,
  activo boolean not null default true,
  fecha_creacion timestamptz not null default now()
);

create table public.lotes (
  id uuid primary key default gen_random_uuid(),
  producto_id uuid not null references public.productos(id) on delete cascade,
  numero_lote text not null,
