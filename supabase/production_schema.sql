create or replace function public.cerrar_arqueo(
  p_efectivo_contado numeric,
  p_gastos_dia numeric default 0,
  p_retiros_caja numeric default 0,
  p_justificacion text default null,
  p_autorizado_por uuid default null
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_arqueo record;
  v_efectivo numeric(10,2);
  v_tarjeta numeric(10,2);
  v_credito numeric(10,2);
  v_diferencia numeric(10,2);
begin
  if v_user_id is null then
    raise exception 'No autenticado' using errcode = '28000';
  end if;

  if p_efectivo_contado < 0 or p_gastos_dia < 0 or p_retiros_caja < 0 then
    raise exception 'Montos invalidos';
  end if;

  select *
  into v_arqueo
  from public.arqueos_caja
  where usuario_id = v_user_id
    and fecha = current_date
    and estado = 'ABIERTO'
  for update;

  if not found then
    raise exception 'No hay caja abierta para cerrar';
  end if;

  select
    coalesce(sum(total) filter (where forma_pago = 'EFECTIVO' and estado = 'CERRADA'), 0),
    coalesce(sum(total) filter (where forma_pago in ('QR', 'TARJETA') and estado = 'CERRADA'), 0),
    coalesce(sum(total) filter (where forma_pago = 'CREDITO' and estado = 'CERRADA'), 0)
  into v_efectivo, v_tarjeta, v_credito
  from public.ventas
  where usuario_id = v_user_id
    and fecha >= v_arqueo.hora_apertura
    and fecha <= now();

  v_diferencia := p_efectivo_contado - (v_arqueo.fondo_inicial + v_efectivo - p_gastos_dia - p_retiros_caja);

  if abs(v_diferencia) > 10 then
    if p_autorizado_por is null or not exists (
      select 1
      from public.perfiles
      where id = p_autorizado_por
        and rol = 'ADMIN'
        and activo = true
    ) then
      raise exception 'Diferencia requiere autorizacion de administrador';
    end if;

    if nullif(trim(coalesce(p_justificacion, '')), '') is null then
      raise exception 'Diferencia requiere justificacion';
    end if;
  end if;

  update public.arqueos_caja
  set hora_cierre = now(),
      ventas_efectivo = v_efectivo,
      ventas_tarjeta = v_tarjeta,
      ventas_credito = v_credito,
      gastos_dia = p_gastos_dia,
      retiros_caja = p_retiros_caja,
      efectivo_contado = p_efectivo_contado,
      justificacion = nullif(trim(coalesce(p_justificacion, '')), ''),
      autorizado_por = p_autorizado_por,
      estado = 'CERRADO'
  where id = v_arqueo.id;

  return v_arqueo.id;
end;
$$;

revoke all on function public.cerrar_arqueo(numeric, numeric, numeric, text, uuid) from public, anon;
grant execute on function public.cerrar_arqueo(numeric, numeric, numeric, text, uuid) to authenticated;

