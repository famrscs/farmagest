create or replace function public.abrir_arqueo(p_fondo_inicial numeric)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_arqueo_id uuid;
begin
  if v_user_id is null then
    raise exception 'No autenticado' using errcode = '28000';
  end if;

  if p_fondo_inicial < 0 then
    raise exception 'Fondo inicial invalido';
  end if;

  insert into public.arqueos_caja (usuario_id, fecha, fondo_inicial)
  values (v_user_id, current_date, p_fondo_inicial)
  returning id into v_arqueo_id;

  return v_arqueo_id;
end;
$$;

