  factura_compra text,
  unique (producto_id, numero_lote)
);

create table public.ventas (
  id uuid primary key default gen_random_uuid(),
  usuario_id uuid not null references public.perfiles(id),
  fecha timestamptz not null default now(),
  subtotal numeric(10,2) not null check (subtotal >= 0),
  descuento numeric(10,2) not null default 0 check (descuento >= 0),
  iva numeric(10,2) not null default 0 check (iva >= 0),
  total numeric(10,2) not null check (total >= 0),
  forma_pago public.forma_pago not null,
  cliente_nombre text,
  cliente_telefono text,
  estado public.estado_venta not null default 'CERRADA',
  fecha_anulacion timestamptz,
  motivo_anulacion text,
  numero_ticket bigint generated by default as identity unique
