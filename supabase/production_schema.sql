create or replace function public.anular_venta(
  p_venta_id uuid,
  p_motivo text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_venta record;
  v_detalle record;
begin
  if v_user_id is null then
    raise exception 'No autenticado' using errcode = '28000';
  end if;

  select *
  into v_venta
  from public.ventas
  where id = p_venta_id
  for update;

  if not found then
    raise exception 'Venta no encontrada';
  end if;

  if v_venta.usuario_id <> v_user_id and not private.is_admin() then
    raise exception 'No autorizado' using errcode = '42501';
  end if;

  if v_venta.estado = 'ANULADA' then
    raise exception 'La venta ya fue anulada';
  end if;

  for v_detalle in
    select lote_id, cantidad
    from public.detalle_ventas
    where venta_id = p_venta_id
    for update
  loop
    update public.lotes
    set cantidad_disponible = cantidad_disponible + v_detalle.cantidad
    where id = v_detalle.lote_id;
  end loop;

  update public.ventas
  set estado = 'ANULADA',
      fecha_anulacion = now(),
      motivo_anulacion = nullif(trim(p_motivo), '')
  where id = p_venta_id;

  return true;
end;
$$;

revoke all on function public.anular_venta(uuid, text) from public, anon;
grant execute on function public.anular_venta(uuid, text) to authenticated;

create or replace function public.obtener_ticket(p_venta_id uuid)
