    'fecha', v.fecha,
    'formaPago', v.forma_pago,
    'estado', v.estado,
    'subtotal', v.subtotal,
    'descuento', v.descuento,
    'iva', v.iva,
    'total', v.total,
    'items', coalesce(
      jsonb_agg(
        jsonb_build_object(
          'producto', p.nombre_comercial,
          'presentacion', p.presentacion,
          'lote', l.numero_lote,
          'cantidad', d.cantidad,
          'precioUnitario', d.precio_unitario,
          'subtotal', d.subtotal
        )
        order by p.nombre_comercial
      ) filter (where d.id is not null),
      '[]'::jsonb
    )
  )
  from public.ventas v
  left join public.detalle_ventas d on d.venta_id = v.id
  left join public.productos p on p.id = d.producto_id
  left join public.lotes l on l.id = d.lote_id
  where v.id = p_venta_id
  group by v.id;
$$;

